# --------------------------------------------------------------------- API client
class ApiClient:
    def __init__(self, base: str):
        self.base = base + "/api"
        self.http = requests.Session()

    def get(self, path, **kw):
        return self.http.get(self.base + path, timeout=5, **kw)

    def post(self, path, payload=None, **kw):
        return self.http.post(self.base + path, json=payload, timeout=5, **kw)

    def delete(self, path, **kw):
        return self.http.delete(self.base + path, timeout=5, **kw)

    # helpers that keep tests short and readable
    def new_cart(self) -> str:
        resp = self.post("/carts")
        assert resp.status_code == 201, resp.text
        return resp.json()["cart_id"]

    def add(self, cart_id, product_id, quantity=1):
        return self.post(f"/carts/{cart_id}/items", {"product_id": product_id, "quantity": quantity})

    def cart(self, cart_id, province="ON"):
        return self.get(f"/carts/{cart_id}", params={"province": province})

    def discount(self, cart_id, code):
        return self.post(f"/carts/{cart_id}/discount", {"code": code})

    def checkout(self, cart_id, email="shopper@example.com", province="ON"):
        return self.post(f"/carts/{cart_id}/checkout", {"email": email, "province": province})


