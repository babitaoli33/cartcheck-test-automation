# --------------------------------------------------------------------- contracts
_schemas: dict[str, dict] = {}


def assert_matches_schema(data, name: str) -> None:
    if name not in _schemas:
        _schemas[name] = json.loads((SCHEMA_DIR / f"{name}.json").read_text())
    jsonschema.validate(data, _schemas[name])


def load_json(name: str):
    return json.loads((DATA_DIR / name).read_text())


# --------------------------------------------------------------------- traceability
_req_map: dict[str, list[str]] = defaultdict(list)
_outcomes: dict[str, str] = {}


def pytest_collection_modifyitems(items):
    for item in items:
        for mark in item.iter_markers("req"):
            for req_id in mark.args:
                if req_id not in REQUIREMENTS:
                    raise pytest.UsageError(f"{item.nodeid} links unknown requirement {req_id}")
                _req_map[req_id].append(item.nodeid)


def pytest_runtest_logreport(report):
    if report.when == "call" or (report.when == "setup" and report.outcome != "passed"):
        if hasattr(report, "wasxfail"):
            bug = re.match(r"(BUG-\d+)", report.wasxfail.replace("reason: ", ""))
            _outcomes[report.nodeid] = f"known bug {bug.group(1)}" if bug else "xfail"
        else:
            _outcomes[report.nodeid] = report.outcome


def pytest_sessionfinish(session):
    if not _outcomes:
        return
    lines = ["# Requirements traceability matrix", "",
             "Generated by the test run (`tests/conftest.py`). One row per requirement.", "",
             "| Requirement | Description | Tests | Result |", "|---|---|---|---|"]
    for req_id, text in REQUIREMENTS.items():
        tests = [t for t in _req_map.get(req_id, []) if t in _outcomes]
        if not tests:
            lines.append(f"| {req_id} | {text} | 0 | NOT COVERED |")
            continue
        results = [_outcomes[t] for t in tests]
        bugs = sorted({r.split()[-1] for r in results if r.startswith("known bug")})
        failed = sum(r == "failed" for r in results)
        status = "FAIL" if failed else ("Known defect: " + ", ".join(bugs) if bugs else "PASS")
        lines.append(f"| {req_id} | {text} | {len(tests)} | {status} |")
    out = ROOT / "reports" / "traceability.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
